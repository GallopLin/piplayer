#!/bin/bash
# CheckFreq Recovery Benchmark: multiple runs for CheckFreq and standard PyTorch resume
# Usage: bash run_recovery_benchmark_checkfreq.sh [num_runs]
#
# Prerequisites:
#   - A valid CheckFreq checkpoint (.chk file) must exist
#   - A valid standard PyTorch checkpoint must exist (accelerator.save_state format)
#   - Adjust paths below to match your environment

NUM_RUNS=${1:-5}
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

HOME_DIR="$HOME"
MODEL="facebook/opt-1.3b"
DATASET="wikitext"
DATASET_CONFIG="wikitext-2-raw-v1"
BATCH_SIZE=1
EPOCHS=1

# ============ Paths - ADJUST THESE ============
# CheckFreq checkpoint paths
CHECKFREQ_OUTPUT_DIR="${HOME_DIR}/download/ckpt_checkfreq"
CHECKFREQ_RESUME_DIR="${CHECKFREQ_OUTPUT_DIR}/step_1"
# Path to the .chk file generated by CheckFreq save_checkpoint
CHECKFREQ_CHK_PATH="${HOME_DIR}/code/pccheck/checkpoint_eval/pccheck/checkpoint-0-0.chk"

# Standard PyTorch resume
STANDARD_OUTPUT_DIR="${HOME_DIR}/download/ckpt_standard_resume"
STANDARD_RESUME_DIR="${STANDARD_OUTPUT_DIR}/step_1"

# Result directories
RESULT_DIR="${SCRIPT_DIR}/recovery_benchmark_checkfreq_results"
mkdir -p "$RESULT_DIR"

CHECKFREQ_CSV="${RESULT_DIR}/checkfreq_results.csv"
STANDARD_CSV="${RESULT_DIR}/standard_results.csv"

echo "========================================="
echo "CheckFreq Recovery Benchmark"
echo "Runs per method: ${NUM_RUNS}"
echo "========================================="

# Detect python in pccheck conda env
PYTHON_CMD="python"
if command -v conda &> /dev/null; then
    CONDA_BASE=$(conda info --base 2>/dev/null)
    if [ -d "${HOME_DIR}/anaconda3/envs/pccheck" ]; then
        PYTHON_CMD="${HOME_DIR}/anaconda3/envs/pccheck/bin/python"
    fi
fi
echo "Using Python: ${PYTHON_CMD}"

# ---- CheckFreq Recovery ----
echo ""
echo "===== CheckFreq Recovery ====="

# Remove old CSV to start fresh
rm -f "${CHECKFREQ_OUTPUT_DIR}/training_time_log.csv"
mkdir -p "${CHECKFREQ_OUTPUT_DIR}"

for i in $(seq 1 $NUM_RUNS); do
    echo ""
    echo "--- CheckFreq Run $i / $NUM_RUNS ---"
    $PYTHON_CMD run_clm_checkfreq2.py \
        --model_name_or_path "$MODEL" \
        --dataset_name "$DATASET" \
        --dataset_config_name "$DATASET_CONFIG" \
        --per_device_train_batch_size $BATCH_SIZE \
        --num_train_epochs $EPOCHS \
        --output_dir "$CHECKFREQ_OUTPUT_DIR" \
        --overwrite_output_dir \
        --use_checkfreq \
        --checkfreq_chk_path "$CHECKFREQ_CHK_PATH" \
        --resume_from_checkpoint "$CHECKFREQ_RESUME_DIR" \
        2>&1 | tee "${RESULT_DIR}/checkfreq_run_${i}.log"

    echo "[OK] CheckFreq run $i complete"
done

# Copy results
if [ -f "${CHECKFREQ_OUTPUT_DIR}/training_time_log.csv" ]; then
    cp "${CHECKFREQ_OUTPUT_DIR}/training_time_log.csv" "$CHECKFREQ_CSV"
    echo "CheckFreq results saved to: $CHECKFREQ_CSV"
fi

# ---- Standard PyTorch Recovery ----
echo ""
echo "===== Standard PyTorch Recovery ====="

rm -f "${STANDARD_OUTPUT_DIR}/training_time_log.csv"
mkdir -p "${STANDARD_OUTPUT_DIR}"

for i in $(seq 1 $NUM_RUNS); do
    echo ""
    echo "--- Standard Run $i / $NUM_RUNS ---"
    $PYTHON_CMD run_clm_checkfreq2.py \
        --model_name_or_path "$MODEL" \
        --dataset_name "$DATASET" \
        --dataset_config_name "$DATASET_CONFIG" \
        --per_device_train_batch_size $BATCH_SIZE \
        --num_train_epochs $EPOCHS \
        --output_dir "$STANDARD_OUTPUT_DIR" \
        --overwrite_output_dir \
        --resume_from_checkpoint "$STANDARD_RESUME_DIR" \
        2>&1 | tee "${RESULT_DIR}/standard_run_${i}.log"

    echo "[OK] Standard run $i complete"
done

if [ -f "${STANDARD_OUTPUT_DIR}/training_time_log.csv" ]; then
    cp "${STANDARD_OUTPUT_DIR}/training_time_log.csv" "$STANDARD_CSV"
    echo "Standard results saved to: $STANDARD_CSV"
fi

echo ""
echo "========================================="
echo "Benchmark complete."
echo "Results in: $RESULT_DIR"
echo "========================================="

# Generate comparison plot if possible
if [ -f "${CHECKFREQ_CSV}" ] && [ -f "${STANDARD_CSV}" ]; then
    echo "Generating comparison plots..."
    $PYTHON_CMD plot_recovery_results_checkfreq.py "$RESULT_DIR"
fi
